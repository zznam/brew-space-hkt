type MerchantKey = keyof typeof merchantMessages.en;

export const MODE_KEYS = {
  METERED_OPEN: 'modeMeteredOpen',
  BUNDLE_2H: 'modeBundle2h',
  BUNDLE_4H: 'modeBundle4h',
} as const satisfies Record<string, MerchantKey>;

const POS_ERROR_KEYS: Record<string, MerchantKey> = {
  'Order not found.': 'errOrderNotFound',
  'Order can no longer be edited.': 'errOrderLocked',
  'Item is sold out.': 'errSoldOut',
  'Invalid quantity.': 'errQuantity',
  'Line not found.': 'errLineNotFound',
  'Order cannot be paid from this state.': 'errCannotPay',
  'Cannot pay an empty order.': 'errEmptyOrder',
  'Only a draft order can be cancelled.': 'errCancelDraftOnly',
};

/** The POS store reports errors in English; unknown ones pass through. */
export function posErrorText(message: string, lang: Lang): string {
  const key = POS_ERROR_KEYS[message];
  return key ? translate(merchantMessages, lang, key) : message;
}

/** Store ticket labels are a seat label or "Walk-in #n". */
export function ticketText(label: string, lang: Lang): string {
  if (lang === 'en') return label;
  return seatLabelText(label, lang).replace(
    /^Walk-in #/,
    translate(merchantMessages, lang, 'walkInTicket'),
  );
}
